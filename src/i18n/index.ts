export type Key = keyof Dict;
const DICTS: Record<Lang, Dict> = { en, th };

export const readLang = (): Lang => {
  try {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "en" || q === "th") return q;
    const s = localStorage.getItem("pixel-truth-lang");
    if (s === "en" || s === "th") return s;
  } catch {
    /* storage ถูกปิด → ใช้ค่าเริ่มต้น */
  }
  return "en";
};

export type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string };
export const I18n = createContext<Ctx | null>(null);

export const translate = (lang: Lang, k: Key, vars?: Record<string, string | number>) =>
  DICTS[lang][k].replace(/\{(\w+)\}/g, (_, v: string) => String(vars?.[v] ?? `{${v}}`));

export function useI18n() {
  const c = useContext(I18n);
  if (!c) throw new Error("useI18n ต้องอยู่ใต้ LangProvider");
  return c;
}
